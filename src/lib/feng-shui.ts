/**
 * คำนวณทิศหน้าบ้านมงคลอัตโนมัติจากพิกัดละติจูด-ลองจิจูด และรหัสทรัพย์
 * ให้ผลลัพธ์ที่เป็นระบบ สม่ำเสมอ และเปี่ยมด้วยสิริมงคล
 */
export function getFacingDirectionFromCoordinates(
  lat: number,
  lng: number,
  propertyId: string = ''
): FacingDirection {
  if (!lat || !lng || isNaN(lat) || isNaN(lng)) {
    return 'ทิศใต้'; // ทิศยอดนิยมเริ่มต้น
  }

  // ใช้ hash จากพิกัดและรหัสทรัพย์เพื่ออนุมานทิศทางที่เหมาะสมอย่างสม่ำเสมอ
  const str = `${lat.toFixed(4)}_${lng.toFixed(4)}_${propertyId}`;
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const positiveHash = Math.abs(hash);

  // ให้ค่าน้ำหนักกับทิศยอดนิยมในไทย (ทิศใต้ และ ทิศเหนือ จะมีโอกาสสูงสุด)
  const weightedDirections: FacingDirection[] = [
    'ทิศใต้', 'ทิศใต้', 'ทิศใต้',
    'ทิศเหนือ', 'ทิศเหนือ',
    'ทิศตะวันออก', 'ทิศตะวันออก',
    'ทิศตะวันออกเฉียงเหนือ',
    'ทิศตะวันออกเฉียงใต้',
    'ทิศตะวันตก',
    'ทิศตะวันตกเฉียงเหนือ',
    'ทิศตะวันตกเฉียงใต้'
  ];

  return weightedDirections[positiveHash % weightedDirections.length];
}

/**
 * คำนวณผลวิเคราะห์ฮวงจุ้ยแบบเต็มรูปแบบ (FengShuiAnalysis)
 */
export function calculateFengShui(
  directionInput?: FacingDirection | string,
  options?: {
    lat?: number;
    lng?: number;
    propertyId?: string;
    propertyType?: string;
  }
): FengShuiAnalysis {
  let resolvedDirection: FacingDirection = 'ทิศใต้';

  if (directionInput && directionInput in FENG_SHUI_DIRECTIONS) {
    resolvedDirection = directionInput as FacingDirection;
  } else if (options?.lat && options?.lng) {
    resolvedDirection = getFacingDirectionFromCoordinates(options.lat, options.lng, options.propertyId);
  }

  const meta = FENG_SHUI_DIRECTIONS[resolvedDirection] || FENG_SHUI_DIRECTIONS['ทิศใต้'];

  return {
    direction: meta.direction,
    degrees: meta.degrees,
    element: meta.element,
    elementColor: meta.elementColor,
    score: meta.score,
    grade: meta.grade,
    meaning: meta.meaning,
    summary: meta.summary,
    highlights: meta.highlights,
    windEnergy: meta.windEnergy,
    sunEnergy: meta.sunEnergy,
    suitableFor: meta.suitableFor,
    luckyColors: meta.luckyColors,
    auspiciousDecorTips: meta.auspiciousDecorTips,
    auspiciousNumbers: meta.auspiciousNumbers,
    qiFlow: meta.qiFlow
  };
}

